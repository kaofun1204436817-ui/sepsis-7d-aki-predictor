drop table if exists vit_pre;
create temp table vit_pre as
select s.patientunitstayid,
  min(v.temperature) as temp_pre_min, max(v.temperature) as temp_pre_max,
  min(v.sao2) as spo2_pre_min, max(v.sao2) as spo2_pre_max,
  min(v.heartrate) as hr_pre_min, max(v.heartrate) as hr_pre_max,
  min(v.respiration) as rr_pre_min, max(v.respiration) as rr_pre_max,
  min(v.systemicsystolic) as sbp_pre_min, max(v.systemicsystolic) as sbp_pre_max,
  min(v.systemicdiastolic) as dbp_pre_min, max(v.systemicdiastolic) as dbp_pre_max,
  min(v.systemicmean) as mbp_pre_min, max(v.systemicmean) as mbp_pre_max,
  count(*) as n_vit_pre
from coh2 s join vitalperiodic v on v.patientunitstayid = s.patientunitstayid
  and v.observationoffset > s.t0 - 1440 and v.observationoffset <= s.t0
group by s.patientunitstayid;

